<details class="wp-block-details abr-faq" open><summary>What are the Abrahamic religions?</summary><!-- wp:paragraph -->
<p>The term refers to religious traditions that trace a spiritual or historical connection to Abraham: Judaism, Christianity, Islam and the far smaller Mandaeism.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"abr-faq"} -->
<details class="wp-block-details abr-faq"><summary>Why are these religions called Abrahamic?</summary><!-- wp:paragraph -->
<p>Each tradition looks back to Abraham as a foundational figure. Jewish tradition regards him as the father of the Jewish people; Christian theology holds him up as a model of faith; Islamic tradition honours him as a prophet and the father of Ishmael and Isaac. Mandaeism is the exception: it shares the prophets from Adam to Shem, honours John the Baptist above all, and does not count Abraham a prophet.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"abr-faq"} -->
<details class="wp-block-details abr-faq"><summary>Who was Abraham?</summary><!-- wp:paragraph -->
<p>Abraham is a figure of the ancient Near East who appears in the Torah, the Bible, and the Qur’an. Tradition holds that he answered a divine call to leave his homeland and entered into a covenant with God.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"abr-faq"} -->
<details class="wp-block-details abr-faq"><summary>What do the Abrahamic religions have in common?</summary><!-- wp:paragraph -->
<p>They share a heritage centred on Abraham, belief in one God, reverence for scripture, and overlapping narratives and figures. Their theological interpretations and religious practices nonetheless differ significantly.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"abr-faq"} -->
<details class="wp-block-details abr-faq"><summary>How do the four traditions differ?</summary><!-- wp:paragraph -->
<p>They differ in their understanding of God, most visibly between Trinitarian doctrine and strict monotheism; in their sacred texts; in their view of Jesus; and in religious practice. Judaism centres on Torah and its interpretation, Christianity on the person of Jesus, and Islam on the Qur’an and the prophetic example of Muhammad. Mandaeism centres on baptism in running water and on the knowledge kept by its hereditary priesthood.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"abr-faq"} -->
<details class="wp-block-details abr-faq"><summary>Are all Abrahamic religions monotheistic?</summary><!-- wp:paragraph -->
<p>All four affirm one God, though they understand that God differently. Judaism stresses the oneness of God; Christianity affirms the Trinity; Islam insists on tawhid (<span lang="ar" dir="rtl">توحيد</span>, the absolute oneness of God); Mandaeism worships the Great Life, set against a world of darkness.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"abr-faq"} -->
<details class="wp-block-details abr-faq"><summary>Which sacred texts belong to the Abrahamic religions?</summary><!-- wp:paragraph -->
<p>Judaism reads the Torah, the wider Tanakh, and rabbinic literature. Christianity reads the Old and New Testaments. Islam reads the Qur’an alongside the Hadith. Mandaeism reads the Ginza Rabba and the Qolasta. Each tradition also carries an extensive interpretive literature.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"abr-faq"} -->
<details class="wp-block-details abr-faq"><summary>Why is Jerusalem important to multiple religions?</summary><!-- wp:paragraph -->
<p>Jerusalem is sacred to Judaism as the site of the ancient Temple, to Christianity as the place of the crucifixion and, in Christian belief, the resurrection of Jesus, and to Islam as the site of al-Masjid al-Aqsa and the Dome of the Rock, associated with the Prophet’s Night Journey.</p>
<!-- /wp:paragraph -->
</details>
